//! The running score: material plus piece-square bonuses, kept up to date
//! as pieces are put down and removed.

use crate::{
    board::Board,
    types::{Color, Piece, PieceKind, Square},
};

impl Board {
    /// The material and piece-square score in centipawns from White's point
    /// of view: White's pieces count up, Black's count down.
    #[must_use]
    pub(crate) const fn score(&self) -> i32 {
        self.score
    }
}

/// What `piece` standing on `sq` adds to the score, from White's point of
/// view. [`Board`] adds it when the piece is put down and subtracts it when
/// the piece is removed.
pub fn piece_score(piece: Piece, sq: Square) -> i32 {
    let kind = piece.kind();
    let color = piece.color();
    let value = material_value(kind).saturating_add(square_bonus(kind, color, sq));

    match color {
        Color::White => value,
        Color::Black => value.saturating_neg(),
    }
}

pub const fn material_value(kind: PieceKind) -> i32 {
    match kind {
        PieceKind::Pawn => 100,
        PieceKind::Knight | PieceKind::Bishop => 300,
        PieceKind::Rook => 500,
        PieceKind::Queen => 900,
        PieceKind::King => 0,
    }
}

