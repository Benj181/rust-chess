//! Position evaluation: how good a position is, as a number.

use crate::{
    board::Board,
    types::{Color, PieceKind, Square},
};

/// Scores `board` in centipawns (100 = one pawn) from the point of view of
/// the side to move: positive is good for them, negative for the opponent.
///
/// It counts material plus a bonus for where each piece stands
/// (piece-square tables).
#[must_use]
pub fn evaluate(board: &Board) -> i32 {
    let me = board.side_to_move();

    let mine = side_score(board, me);
    let theirs = side_score(board, me.opposite());

    mine.saturating_sub(theirs)
}

fn side_score(board: &Board, color: Color) -> i32 {
    let material = i32::try_from(board.material(color))
        .unwrap_or(0)
        .saturating_mul(100);
    material.saturating_add(
        PieceKind::ALL
            .into_iter()
            .flat_map(|kind| {
                board
                    .pieces_of(color, kind)
                    .into_iter()
                    .map(move |sq| square_bonus(kind, color, sq))
            })
            .sum(),
    )
}

